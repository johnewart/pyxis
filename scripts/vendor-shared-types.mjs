#!/usr/bin/env node
// Copies @pyxis-llm/client's zero-dependency shared types (messages.ts and
// conversationEvents.ts — the Message classes and the ConversationEvent
// union/enum) into <target-package>/src/vendor/llmd-types/ at build time, and
// writes an index.ts re-exporting them.
//
// This lets @pyxis-llm/react use those types WITHOUT depending on a client package.
// @pyxis-llm/react declares @pyxis-llm/client as an OPTIONAL peer dependency on purpose:
// a host that can't import a transport client in the process rendering
// ChatPanel (a renderer with contextIsolation, or a browser talking to its
// own backend) supplies its own object satisfying ChatStreamCapableClient. But
// useLlmdChatDriver imports RUNTIME values — ConversationEventType, and
// UserMessage, which it constructs — not just types, so it cannot use a
// type-only import. Vendoring compiles them into @pyxis-llm/react's own dist and
// keeps the peer dependency genuinely optional.
//
// Publishing note (the original incident): an npm `file:` dependency is
// published VERBATIM — npm does not rewrite it — so shipping
// "@pyxis-llm/client": "file:../client" produces a package nobody can install.
// Vendoring sidesteps that for @pyxis-llm/react entirely. Anything that publishes a
// package with a real `file:` dependency must rewrite that specifier to a
// version first.
//
// The copied files are gitignored (packages/*/src/vendor/); every build
// re-copies from packages/client/src, which stays the single editable source
// of truth.
//
// Usage: node scripts/vendor-shared-types.mjs <package-dir>
//   e.g. node scripts/vendor-shared-types.mjs packages/react

import { copyFileSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, '..');

const targetArg = process.argv[2];
if (!targetArg) {
  console.error('Usage: node scripts/vendor-shared-types.mjs <package-dir>');
  process.exit(1);
}

// Keep this list to modules with NO imports of their own, OR whose imports are
// themselves in this list — they are compiled standalone into the consumer's
// dist, so anything they import has to be vendored too. (conversationEvents.ts
// imports QueuedMessage from sessionQueue.ts, which is why that one is here:
// dropping it silently breaks @pyxis-llm/react's build, not @pyxis-llm/client's.)
const SOURCES = ['messages.ts', 'sessionQueue.ts', 'conversationEvents.ts'];

const sourceDir = path.join(repoRoot, 'packages', 'client', 'src');
const destDir = path.join(repoRoot, targetArg, 'src', 'vendor', 'llmd-types');

rmSync(destDir, { recursive: true, force: true });
mkdirSync(destDir, { recursive: true });

for (const file of SOURCES) {
  copyFileSync(path.join(sourceDir, file), path.join(destDir, file));
}

writeFileSync(
  path.join(destDir, 'index.ts'),
  `// @generated by scripts/vendor-shared-types.mjs — do not edit.
// Source of truth: packages/client/src/{${SOURCES.join(',')}}
export * from './messages.js';
export * from './sessionQueue.js';
export * from './conversationEvents.js';
`
);

console.log(`vendored ${SOURCES.length} shared type modules -> ${targetArg}/src/vendor/llmd-types/`);
